import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
const require = createRequire('file:///D:/UserFolders/Desktop/qingchuang-pinpin/tests/');
const { chromium } = require('playwright');
const out = 'D:/UserFolders/Desktop/qingchuang-pinpin/项目资料/上架调试/lead/sunshots';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push('console:' + m.text()); });
await page.goto('http://127.0.0.1:4173/preview/', { waitUntil: 'networkidle' });
await page.locator('#universe-canvas').waitFor({ state: 'visible' });
await page.waitForTimeout(1200);
await page.screenshot({ path: join(out, 'home-full.png') });
await page.locator('#universe-canvas').screenshot({ path: join(out, 'home-canvas.png') });
await page.waitForTimeout(1500);
await page.locator('#universe-canvas').screenshot({ path: join(out, 'home-canvas-2.png') });
console.log(JSON.stringify({ errors, box: await page.locator('#universe-canvas').boundingBox() }));
await browser.close();
