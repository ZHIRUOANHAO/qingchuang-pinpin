import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const defaultWorkbench = path.join(root, '项目资料', '文档与案例工作区', '轻创拼拼项目工作台')
const workbench = process.argv[2] ? path.resolve(process.argv[2]) : defaultWorkbench
const sourceDir = path.join(workbench, '02_轻资产案例库', '数据')
const outputDir = path.join(root, 'miniprogram', 'data')
const previewOutputDir = path.join(root, 'preview')

function readJson(name) {
  return JSON.parse(fs.readFileSync(path.join(sourceDir, name), 'utf8'))
}

function writeModule(name, exportName, value) {
  const banner = `// Generated by scripts/import-case-library.mjs from the canonical project workbench.\n// Public case fields only. Do not edit by hand or include internal research and credentials.\n`
  const code = `${banner}const ${exportName} = ${JSON.stringify(value)}\n\nmodule.exports = { ${exportName} }\n`
  fs.writeFileSync(path.join(outputDir, name), code, 'utf8')
}

function writeWebCaseLibrary(catalog, freeDetails, metadata) {
  const banner = `// Generated by scripts/import-case-library.mjs from the canonical project workbench.\n// Public case fields only. Do not edit by hand or include internal research and credentials.\n`
  const code = `${banner}export const caseCatalog = ${JSON.stringify(catalog)}\n\nexport const freeCaseDetails = ${JSON.stringify(freeDetails)}\n\nexport const caseLibraryMeta = ${JSON.stringify(metadata)}\n`
  fs.writeFileSync(path.join(previewOutputDir, 'case-library.js'), code, 'utf8')
}

function markLocalIntegrationComplete() {
  const validationPath = path.join(sourceDir, '生成校验记录.json')
  if (!fs.existsSync(validationPath)) return

  const validation = JSON.parse(fs.readFileSync(validationPath, 'utf8'))
  const updated = {
    ...validation,
    integrated_to_local_miniprogram: true,
    local_miniprogram_target: root,
    local_integration_date: new Date().toISOString().slice(0, 10),
    published_to_app: false,
    payment_implemented: false
  }
  fs.writeFileSync(validationPath, `${JSON.stringify(updated, null, 2)}\n`, 'utf8')
}

const catalogDocument = readJson('案例目录_公开.json')
const freeDocument = readJson('免费案例全文_公开.json')
const accessPolicy = readJson('案例访问规则.json')
// Explicit projection prevents future editorial notes or credentials from being
// copied into either client merely because every case is now free to read.
function pick(value, keys) {
  return Object.fromEntries(keys.filter(key => Object.hasOwn(value, key)).map(key => [key, value[key]]))
}
const detailById = new Map(freeDocument.cases.map(item => [item.id, item]))
function publicSources(item, catalogItem) {
  assert.ok(Array.isArray(item.factualBasis?.sources) && item.factualBasis.sources.length, `${item.id}: public proof sources are required`)
  assert.equal(item.factualBasis.checkedOn, catalogItem.evidenceCheckedOn, `${item.id}: evidence dates must agree`)
  return item.factualBasis.sources.map((source, index) => {
    const url = new URL(source.url)
    assert.equal(url.protocol, 'https:', `${item.id}: evidence URL must use HTTPS`)
    assert.ok(!url.username && !url.password, `${item.id}: evidence URL must not include credentials`)
    assert.ok(catalogItem.sourceUrls.includes(source.url), `${item.id}: evidence URL must appear in the public catalog`)
    assert.equal(source.checked_on, item.factualBasis.checkedOn, `${item.id}: source and observation dates must agree`)
    assert.ok(source.access && source.publisher, `${item.id}: source type and publisher are required`)
    return {
      label: source.title || source.name || `来源 ${index + 1}`,
      url: source.url,
      host: url.hostname.replace(/^www\./, ''),
      checkedOn: source.checked_on,
      access: source.access,
      publisher: source.publisher
    }
  })
}
const catalog = catalogDocument.cases.map(item => {
  const detail = detailById.get(item.id)
  assert.ok(detail, `${item.id}: public detail is required`)
  const sources = publicSources(detail, item)
  return {
    ...pick(item, ['id', 'name', 'industry', 'tags', 'difficulty', 'cost', 'valueProposition', 'offer', 'payer', 'purchaseReason', 'evidenceCheckedOn', 'access', 'accessLabel', 'complianceHint', 'sourceUrls', 'publicationStatus']),
    sourceTier: sources.some(source => source.access === '官方公开页面') ? 'official_page' : 'official_index'
  }
})
const freeDetails = freeDocument.cases.map(item => ({
  ...pick(item, ['id', 'name', 'industry', 'difficulty', 'cost', 'access', 'accessLabel', 'chainSummary', 'complianceHint', 'delivery', 'chargingModel', 'moneyFlow', 'principle']),
  startupCost: pick(item.startupCost, ['experimentCashCNY']),
  acquisition: pick(item.acquisition, ['visibleChannels']),
  requirements: pick(item.requirements, ['skills']),
  factualBasis: { ...pick(item.factualBasis, ['observation', 'checkedOn']), sources: publicSources(item, catalog.find(entry => entry.id === item.id)) },
  validation: pick(item.validation, ['firstAction', 'budgetType', 'measure', 'stopCondition']),
  stages: item.stages.map(stage => pick(stage, ['number', 'name', 'type', 'action', 'transformation', 'reusableUnit', 'epistemicStatus']))
}))

assert.equal(catalog.length, 100, 'The public catalog must contain 100 cases')
assert.equal(freeDetails.length, 100, 'The client bundle must contain all 100 free full cases')
assert.equal(catalog.filter(item => item.access === 'free').length, 100, 'Every current case must be free')
assert.equal(catalog.filter(item => item.access === 'paid').length, 0, 'The free-first library has no paid cases')
assert.equal(new Set(catalog.map(item => item.id)).size, 100, 'Case ids must be unique')
assert.deepEqual(freeDetails.map(item => item.id), accessPolicy.free_case_ids, 'Free details must match the access policy')
assert.deepEqual(freeDetails.map(item => item.id), catalog.map(item => item.id), 'Every catalog entry must have matching free details')
assert.equal(accessPolicy.default_access, 'free')
assert.equal(accessPolicy.unknown_case_access, 'deny')
assert.ok(freeDetails.every(item => item.access === 'free' && item.stages?.length === 7), 'Every free detail must contain seven stages')
assert.ok(catalog.every(item => !('stages' in item) && !('moneyFlow' in item) && !('validation' in item)), 'The index stays lightweight; full case fields live in the detail bundle')

fs.mkdirSync(outputDir, { recursive: true })
fs.mkdirSync(previewOutputDir, { recursive: true })
writeModule('case-catalog.js', 'caseCatalog', catalog)
writeModule('case-free-details.js', 'freeCaseDetails', freeDetails)
const metadata = {
  version: catalogDocument.version,
  lastUpdated: catalogDocument.last_updated,
  total: catalog.length,
  officialPageCount: catalog.filter(item => item.sourceTier === 'official_page').length,
  indexOnlyCount: catalog.filter(item => item.sourceTier === 'official_index').length,
  free: freeDetails.length,
  paid: catalog.filter(item => item.access === 'paid').length,
  paidFullTextBundled: false,
  pricingStatus: accessPolicy.pricing_status,
  adsEnabled: false,
  implementationStatus: '100条案例七关全文免费阅读；未接真实广告或支付，未发布'
}
writeModule('case-library-meta.js', 'caseLibraryMeta', metadata)
writeWebCaseLibrary(catalog, freeDetails, metadata)
markLocalIntegrationComplete()

console.log(`Case library imported: ${catalog.length} catalog / ${freeDetails.length} free full text / 0 paid cases; public fields only`)
